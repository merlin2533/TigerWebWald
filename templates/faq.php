            <!-- 4. Kosten -->
            <details class="faq-eintrag aufdecken">
                <summary class="faq-frage">
                    <span>Was kostet ein Betreuungsplatz?</span>
                    <svg class="faq-pfeil" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M6 9l6 6 6-6"/></svg>
                </summary>
                <div class="faq-antwort">
                    <p>Die Kosten der Kindertagespflege werden in Baden-Württemberg größtenteils vom <strong>Jugendamt (öffentliche Hand)</strong> getragen. Der Betreuungssatz liegt bei ca. <strong>7,50 € pro Stunde</strong> für Kinder unter 3 Jahren und wird direkt an die Tagespflegepersonen gezahlt.</p>
                    <p>Eltern zahlen einen <strong>einkommensabhängigen Elternbeitrag</strong> an die Gemeinde — vergleichbar mit den Gebühren für einen Kita-Platz. Zusätzlich kann ein Beitrag für <strong>Verpflegung (Essensgeld)</strong> anfallen.</p>
                    <p>Für genaue Informationen zu den aktuellen Elternbeiträgen kontaktieren Sie uns gerne oder wenden Sie sich an die <strong>Gemeinde Walddorfhäslach</strong> bzw. den <strong>Tagesmutterverein Reutlingen</strong>.</p>
                </div>
            </details>

            <!-- 5. Eingewöhnung -->
            <details class="faq-eintrag aufdecken">
                <summary class="faq-frage">
                    <span>Wie läuft die Eingewöhnung ab?</span>
                    <svg class="faq-pfeil" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M6 9l6 6 6-6"/></svg>
                </summary>
                <div class="faq-antwort">
                    <p>Die Eingewöhnung orientiert sich am <strong>Berliner Eingewöhnungsmodell</strong> und dauert in der Regel <strong>2 bis 4 Wochen</strong> — je nach Bedürfnis des Kindes auch länger. Die sanfte Eingewöhnung ist uns besonders wichtig, denn eine sichere Bindung zur Tagespflegeperson ist die Grundlage für das Wohlbefinden Ihres Kindes.</p>
                    <p><strong>Ablauf der Eingewöhnung:</strong></p>
                    <ul>
                        <li><strong>Grundphase (Tag 1–3):</strong> Ein Elternteil begleitet das Kind und bleibt die ganze Zeit in der Einrichtung.</li>
                        <li><strong>Trennungsversuche (ab Tag 4):</strong> Erste kurze Trennungsphasen — das Elternteil bleibt in der Nähe und ist jederzeit erreichbar.</li>
                        <li><strong>Stabilisierung:</strong> Die Trennungszeiten werden schrittweise verlängert. Die Tagespflegeperson übernimmt zunehmend die Rolle der sicheren Bezugsperson.</li>
                        <li><strong>Abschluss:</strong> Das Kind fühlt sich sicher und lässt sich von der Tagespflegeperson trösten und begleiten.</li>
                    </ul>
                    <p>Wir nehmen uns für jede Eingewöhnung ausreichend Zeit und richten uns ganz nach dem <strong>individuellen Tempo Ihres Kindes</strong>.</p>
                </div>
            </details>

