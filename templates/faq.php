            <!-- 1. Was ist Kindertagespflege? -->
            <details class="faq-eintrag aufdecken">
                <summary class="faq-frage">
                    <span>Was ist Kindertagespflege und wie unterscheidet sie sich von einer Kita?</span>
                    <svg class="faq-pfeil" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M6 9l6 6 6-6"/></svg>
                </summary>
                <div class="faq-antwort">
                    <p>Kindertagespflege ist eine gesetzlich anerkannte und gleichwertige Betreuungsform neben der Kindertageseinrichtung (Kita). Bei der Kindertagespflege werden Kinder in einer kleinen, familienähnlichen Gruppe von qualifizierten Tagespflegepersonen betreut — bei uns im EntenbachTigeR in einer Großtagespflege mit maximal <strong>9 Betreuungsplätzen</strong>.</p>
                    <p>Der größte Vorteil gegenüber einer Kita ist die <strong>familiäre Atmosphäre</strong> in einer kleinen Gruppe. Jedes Kind bekommt deutlich mehr individuelle Zuwendung und kann eine enge Bindung zu seinen Bezugspersonen aufbauen. Unsere drei Tagespflegepersonen kennen jedes Kind und seine Bedürfnisse genau.</p>
                    <p>Die Kindertagespflege wird in Baden-Württemberg vom <strong>Tagesmutterverein Reutlingen</strong> (gegründet 1973, ältester Verein dieser Art in Baden-Württemberg) fachlich begleitet und durch das Jugendamt gefördert.</p>
                </div>
            </details>

            <!-- 2. Welche Kinder werden betreut? -->
            <details class="faq-eintrag aufdecken">
                <summary class="faq-frage">
                    <span>Welche Kinder werden bei Ihnen betreut?</span>
                    <svg class="faq-pfeil" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M6 9l6 6 6-6"/></svg>
                </summary>
                <div class="faq-antwort">
                    <p>Wir betreuen <strong>Kinder unter 3 Jahren (U3)</strong> — in der Regel ab einem Alter von ca. 1 Jahr bis zum Übergang in den Kindergarten. Insgesamt stehen <strong>9 Betreuungsplätze</strong> zur Verfügung, die von unseren drei qualifizierten Tagespflegepersonen liebevoll begleitet werden.</p>
                    <p>Seit dem 1. August 2013 haben Kinder ab dem vollendeten ersten Lebensjahr einen <strong>Rechtsanspruch auf einen Betreuungsplatz</strong> in der Kindertagesbetreuung — sowohl in einer Kita als auch in der Kindertagespflege.</p>
                </div>
            </details>

