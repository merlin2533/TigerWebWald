                    <p>Alle drei Tagespflegepersonen bei EntenbachTigeR verfügen über eine <strong>qualifizierte Ausbildung nach dem kompetenzorientierten Qualifizierungshandbuch (QHB)</strong> mit mindestens <strong>160 Unterrichtseinheiten</strong>. Diese umfassende Qualifizierung ist in Baden-Württemberg vorgeschrieben und umfasst Themen wie Pädagogik, Entwicklungspsychologie, Ernährung, Erste Hilfe am Kind und rechtliche Grundlagen.</p>
                    <p>Darüber hinaus nehmen unsere Tagespflegepersonen regelmäßig an <strong>Fortbildungen</strong> teil und werden fachlich durch den <strong>Tagesmutterverein Reutlingen</strong> begleitet. Eine gültige <strong>Pflegeerlaubnis</strong> des Jugendamtes ist selbstverständlich.</p>
                </div>
            </details>

            <!-- 7. Verpflegung -->
            <details class="faq-eintrag aufdecken">
                <summary class="faq-frage">
                    <span>Wie sieht die Verpflegung aus?</span>
                    <svg class="faq-pfeil" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M6 9l6 6 6-6"/></svg>
                </summary>
                <div class="faq-antwort">
                    <p>Bei uns erhalten die Kinder eine <strong>ausgewogene und kindgerechte Verpflegung</strong>. Dazu gehören ein gemeinsames Frühstück, Mittagessen und Nachmittagssnack — je nach gebuchtem Betreuungsmodell.</p>
                    <p>Die Mahlzeiten werden <strong>frisch zubereitet</strong>. Wir achten auf eine abwechslungsreiche Ernährung mit viel Obst, Gemüse und Vollkornprodukten. Auf <strong>Allergien und Unverträglichkeiten</strong> nehmen wir selbstverständlich Rücksicht.</p>
                    <p>Die gemeinsamen Mahlzeiten sind fester Bestandteil unseres Tagesablaufs und fördern das <strong>soziale Miteinander</strong> und die Selbstständigkeit der Kinder.</p>
                </div>
            </details>

