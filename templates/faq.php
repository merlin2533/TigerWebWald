                    <p>Sollte es in Ausnahmefällen zu Einschränkungen kommen, informieren wir Sie rechtzeitig. Der <strong>Tagesmutterverein Reutlingen</strong> unterstützt zusätzlich bei der Organisation von Vertretungslösungen.</p>
